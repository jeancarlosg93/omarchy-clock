import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code = readFileSync(new URL('./bar-plugin/BarModel.js', import.meta.url), 'utf8').replace('.pragma library', '');
const model = vm.createContext({});
vm.runInContext(code, model);
const state = {version:1, enabled:true, updatedAt:10000, clock:{id:'test',kind:'stopwatch',title:'Session',display:'00:05',running:true},clocks:[],runningCount:3};
assert.equal(model.fresh(state, 11000), true);
assert.equal(model.fresh(state, 17000), false);
assert.equal(model.fresh(state, 3000), false);
assert.equal(model.fresh({...state,enabled:false}, 11000), false);
assert.equal(model.fresh({...state,version:2}, 11000), false);
assert.equal(model.fresh(null, 11000), null);
assert.equal(model.label(state), 'Stopwatch 00:05 · +2');
const paused = {...state,runningCount:0,clock:{...state.clock,running:false}};
assert.equal(model.label(paused), 'Stopwatch 00:05 · paused');
assert.match(model.tooltip(paused), /Session.*paused/);
assert.equal(model.label({clock:{}}), '');
console.log('PASS: stale/future/disabled/unsupported state, concurrent clocks, paused resume label and tooltip.');
